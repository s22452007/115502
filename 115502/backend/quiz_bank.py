def sync_quiz_bank(cursor):
    """把擴充題目寫進 quiz_question、修正舊題目；回傳 (新增題數, 修正處數)。cursor 是 sqlite3 cursor。"""
    existing = {row[0] for row in cursor.execute('SELECT question FROM quiz_question').fetchall()}
    added = 0
    for level, question, options, answer in EXTRA_QUESTIONS:
        if question in existing:
            continue
        cursor.execute(
            'INSERT INTO quiz_question (stage, level_tag, question, option_a, option_b, option_c, option_d, correct_answer) '
            'VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
            (STAGE_BY_LEVEL[level], level, question, *options, answer))
        existing.add(question)
        added += 1

    fixed = 0
    for question, column, old, new in FIXES:
        cursor.execute(f'UPDATE quiz_question SET {column} = ? WHERE question = ? AND {column} = ?',
                       (new, question, old))
        fixed += cursor.rowcount
    return added, fixed
